// 只把海边特有的东西（海水、沙、礁石、海风）加进来。这里的落日在缓缓往下落：DUSK 里的每一项都有「日落开始」和「日落结束」两个值，
// paint.js 的 setDusk(k) 按日落的进度 k（0 到 1）在两者之间取；TONES 里是不随日落变的量。
// 'name': '#十六进制' 是颜色，['#十六进制', 倍数] 是带亮度的颜色，数组是向量，数字就是数字。

// 落日：方位朝 -z 略偏 -x（海的方向），始终不变。从头到尾都是一轮贴着海平线的落日：
// 开始时（日心高 ELEV[0] 度）下沿在海平线上方不到一度，结束时（ELEV[1] 度）下面四分之一沉进海平线，一共只落不到半个日面直径
const AZ = Math.atan2(-.97, -.24), ELEV = [3.05, .95];
export const sunDirAt = k => {
  const e = (ELEV[0] + (ELEV[1] - ELEV[0]) * k) * Math.PI / 180;
  return [Math.cos(e) * Math.cos(AZ), Math.sin(e), Math.cos(e) * Math.sin(AZ)];
};
export const SUN_DIR = sunDirAt(0);
